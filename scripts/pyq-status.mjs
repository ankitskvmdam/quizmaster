// Writes docs/pyq-status.md: every downloaded previous-year paper and how far it has got.
//   node scripts/pyq-status.mjs
// Source PDFs live in resources/ (git-ignored); transcripts sit next to them as <name>.transcript.yaml;
// a paper is "in the app" when its file exists under content/exams/ (content/ is what gets pushed to the database).
import fs from 'node:fs'
import path from 'node:path'
import YAML from 'yaml'

// Papers deliberately not published, with the reason.
const NOTES = {
  'cgl-2016-tier1-2016-08-30-shift2': 'skipped: reading its pages trips an API content filter',
  'cgl-2020-tier1-2021-08-23-shift1': 'held back: the copy is missing 30 questions (all of Quantitative Aptitude)',
  'chsl-2018-tier1-2019-07-01-shift3': 'held back: many question images missing from the copy (<80 usable)',
  'chsl-2018-tier1-2019-07-03-shift1': 'held back: many question images missing from the copy (<80 usable)',
  'bpsc-67-prelims-gs': 'cancelled sitting: no official key, answers are AI-worked',
}
const walk = (d) => (fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)])) : [])
const contentFiles = walk('content/exams').map((f) => f.split(path.sep).join('/'))

/** Which content file a source paper became. */
function contentFor(exam, base) {
  if (exam === 'bpsc') {
    const n = base.match(/bpsc-(\d+)/)?.[1]
    const want = base.includes('reexam') ? `${n}th-prelims-reexam` : `${n}(th|st|rd|nd)-prelims(-cancelled)?`
    return contentFiles.find((f) => f.includes('/bpsc/') && new RegExp(`/${want}\\.yaml$`).test(f))
  }
  const slug = base.replace(/^(cgl|chsl)-\d{4}-tier1-/, '')
  return contentFiles.filter((f) => f.includes(`/ssc-${exam}/`) && path.basename(f).startsWith(slug))
}

function rows(exam, dir, isPaper) {
  const pdfs = walk(dir).filter((f) => f.endsWith('.pdf') && isPaper(path.basename(f))).sort()
  return pdfs.map((pdf) => {
    const base = path.basename(pdf, '.pdf')
    const folder = path.dirname(pdf)
    const transcripts = fs.readdirSync(folder).filter((f) => f.startsWith(base) && f.endsWith('.transcript.yaml'))
    let questions = 0
    let reviewed = transcripts.length > 0
    let answered = transcripts.length > 0
    for (const t of transcripts) {
      try {
        const d = YAML.parse(fs.readFileSync(path.join(folder, t), 'utf8'))
        questions += d.questions?.length ?? 0
        reviewed &&= Boolean(d.review)
        answered &&= Boolean(d.answers)
      } catch {
        reviewed = answered = false
      }
    }
    const c = contentFor(exam, base)
    const inApp = Array.isArray(c) ? c.length : c ? 1 : 0
    const note = NOTES[base] ?? (base.includes('memory-based') ? 'not a real paper (coaching-site reconstruction): skip' : '')
    return { year: path.basename(folder), base, transcribed: transcripts.length ? `yes (${questions} q)` : 'no', reviewed, answered, inApp, note }
  })
}

const yn = (b) => (b ? 'yes' : 'no')
const table = (rs) =>
  ['| Folder | Paper | Text | Reviewed | Answers checked | In app | Note |', '|---|---|---|---|---|---|---|']
    .concat(rs.map((r) => `| ${r.year} | ${r.base} | ${r.transcribed} | ${yn(r.reviewed)} | ${yn(r.answered)} | ${r.inApp ? 'yes' : 'no'} | ${r.note} |`))
    .join('\n')
const summary = (rs) => {
  const real = rs.filter((r) => !r.base.includes('memory-based'))
  const todo = real.filter((r) => r.transcribed === 'no' && !r.note)
  const waiting = real.filter((r) => r.transcribed !== 'no' && !r.inApp && !r.note)
  return `${real.length} papers downloaded · ${real.filter((r) => r.transcribed !== 'no').length} with text · ${real.filter((r) => r.inApp).length} in the app · ${waiting.length} with text waiting for review/release · **${todo.length} still to transcribe**`
}

const sections = [
  ['BPSC prelims (General Studies)', rows('bpsc', 'resources/bpsc', (n) => /prelims-gs/.test(n) && !/key/.test(n))],
  ['SSC CGL Tier 1', rows('cgl', 'resources/ssc/cgl-tier1', () => true)],
  ['SSC CHSL Tier 1', rows('chsl', 'resources/ssc/chsl-tier1', () => true)],
]
const out = [
  '# Previous-year papers: what is done and what is left',
  '',
  `Generated by \`node scripts/pyq-status.mjs\` on ${new Date().toISOString().slice(0, 10)}. Re-run it after adding papers.`,
  '',
  '- **Text**: the paper has been turned into text (`<paper>.transcript.yaml` next to the PDF in `resources/`).',
  '- **Reviewed**: a second pass compared the text with the scans.',
  '- **Answers checked**: official answers added and verified by AI, with explanations.',
  '- **In app**: the paper has a file under `content/exams/` (what `content:push` loads into the database).',
  '- BPSC mains papers are downloaded too but are out of scope, so they are not listed.',
  '',
  ...sections.flatMap(([title, rs]) => [`## ${title}`, '', summary(rs), '', table(rs), '']),
].join('\n')
fs.writeFileSync('docs/pyq-status.md', out)
for (const [title, rs] of sections) console.log(title + ': ' + summary(rs).replace(/\*\*/g, ''))
